#!/usr/bin/env node
/**
 * Generates src/lib/build-info.ts with commit SHA, build time, and version.
 * Version is based on commit count (e.g., 0.1.123 where 123 = commit count).
 *
 * CI-first behavior:
 * - In CI (or when FORCE_BUILD_INFO=1), always refresh metadata.
 * - Locally, keep repository clean by default and do not rewrite tracked file.
 * - Local override: LOCAL_BUILD_INFO=1.
 */
const { execSync } = require('child_process');
const { writeFileSync, mkdirSync, readFileSync } = require('fs');
const { join } = require('path');

function safeExec(cmd) {
  try { return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { return null; }
}

const gitSha = process.env.GIT_SHA || safeExec('git rev-parse HEAD') || 'UNKNOWN';
const gitShort = (process.env.GIT_SHA_SHORT || safeExec('git rev-parse --short HEAD') || gitSha.slice(0,7));
const builtAt = new Date().toISOString();

const isCI = String(process.env.CI || '').toLowerCase() === 'true'
  || String(process.env.GITHUB_ACTIONS || '').toLowerCase() === 'true';
const forceWrite = process.env.FORCE_BUILD_INFO === '1';
const allowLocalWrite = process.env.LOCAL_BUILD_INFO === '1';

// Get commit count for version numbering
const commitCount = safeExec('git rev-list --count HEAD') || '0';
const baseVersion = '0.1'; // Can be read from package.json if needed
const version = `${baseVersion}.${commitCount}`;

const outDir = join(process.cwd(), 'src', 'lib');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'build-info.ts');

if (!isCI && !forceWrite && !allowLocalWrite) {
  // Keep local working tree stable by default.
  // This avoids timestamp churn in tracked build-info.ts during dev/build.
  try {
    readFileSync(outFile, 'utf8');
    console.log('[build-info] Skip local rewrite (set LOCAL_BUILD_INFO=1 to refresh).');
    process.exit(0);
  } catch {
    // File missing in local environment (fresh checkout) -> generate once.
  }
}

const content = `// Auto-generated by scripts/generate-build-info.js
export const buildInfo = {
  version: '${version}',
  commit: '${gitSha}',
  commitShort: '${gitShort}',
  builtAt: '${builtAt}',
};
`;

try {
  const existing = readFileSync(outFile, 'utf8');
  if (existing === content) {
    console.log('[build-info] No changes.');
    process.exit(0);
  }
} catch {
  // no-op (file does not exist yet)
}

writeFileSync(outFile, content, 'utf8');
console.log('[build-info] Wrote', outFile, { version, commit: gitShort, builtAt });
